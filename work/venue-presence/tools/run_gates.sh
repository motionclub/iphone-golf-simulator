#!/bin/bash
# Re-runs every automated gate check against work/venue-presence/proof/after and writes work/venue-presence/GATE_RESULTS.txt.
# Needs: the final capture already made with HERO_VENUE_DUMP=1 HERO_VENUE_DUMP_KIT=1 (logs in work/venue-presence/logs/).
ROOT=/Users/adnanyonathan/Documents/Codex/2026-09-20/wh/outputs/iphone-golf-simulator
VP=$ROOT/work/venue-presence
T=$VP/tools
OUT=$VP/GATE_RESULTS.txt
cd "$ROOT" || exit 1
{
echo "GATE RESULTS  $(date '+%Y-%m-%d %H:%M')  (generated by work/venue-presence/tools/run_gates.sh)"
echo
echo "== PLAY_SAFE: play-critical files byte-identical to the hashes taken before this work"
( cd Unity/Assets/Scripts/Tennis && shasum -a 256 -c "$VP/before_code/play_files.sha256" )
echo
echo "   venue + capture files this work changed or added (git status):"
git status --short -- Unity/Assets/Scripts/Tennis/TennisVenue.cs Unity/Assets/Scripts/Tennis/TennisVenueBuilder.cs Unity/Assets/Scripts/Tennis/TennisVenueBuilder.Mesh.cs Unity/Assets/Scripts/Tennis/TennisVenueBuilder.Skyscraper.cs Unity/Assets/Scripts/Tennis/TennisVenueBuilder.Volcano.cs Unity/Assets/Scripts/Tennis/TennisVenueFx.cs Unity/Assets/Editor/TennisVenueCapture.cs | sed 's/^/   /'
echo
echo "== COURT_UNCHANGED (1/3): TennisVenue.cs (DeckHalfX/Z, OverDeck, Drone path and end pose) is the same file"
echo "   before: $(shasum -a 256 "$VP/before_code/TennisVenue.cs.before" | cut -c1-64)"
echo "   now:    $(shasum -a 256 Unity/Assets/Scripts/Tennis/TennisVenue.cs | cut -c1-64)"
echo
echo "== COURT_UNCHANGED (2/3) + NO_RESORT_CLUTTER: kept court kit at identical coordinates; resort dressing (017/020/033) not enabled"
python3 "$T/check_kit.py" "$VP/proof/baseline/kit_before.txt" "$VP/logs/final_capture_skyscraper.log" "$VP/logs/final_capture_volcano.log"
echo
echo "== COURT_UNCHANGED (3/3): painted court lines land on the same pixels in the shipped frame and the new frame"
echo "   sensitivity (a 4x3 px shift must be detected):"; python3 "$T/check_court_frames.py" --selftest "$VP/proof/baseline" | sed 's/^/   /'
python3 "$T/check_court_frames.py" ArtDir/screenshots/venues "$VP/proof/after"
echo
echo "== VOLCANO_LIGHT: lava light on the slab edge (same floor patch, shipped vs after)"
python3 "$T/light_metrics.py" ArtDir/screenshots/venues "$VP/proof/after"
echo
echo "== ball readability (lob band), shipped vs after"
echo "   shipped:"; python3 "$T/ball_contrast.py" ArtDir/screenshots/venues | grep -v resort | sed 's/^/   /'
echo "   after:";   python3 "$T/ball_contrast.py" "$VP/proof/after" | grep -v resort | sed 's/^/   /'
echo
echo "== triangle counts (HERO_VENUE_DUMP=1; static meshes only, particle caps counted separately)"
grep -h "VenueDump\] \(skyscraper\|volcano\)" "$VP/logs/final_capture_skyscraper.log" "$VP/logs/final_capture_volcano.log" | sort -u | sed 's/^/   /'
echo "   baseline (unchanged code, same tool):"
grep -h "VenueDump\] \(skyscraper\|volcano\)" "$VP/logs/baseline_run2.txt" 2>/dev/null | sort -u | sed 's/^/   /'
echo
echo "== SKY_HEIGHT: facade families and tower silhouettes"
grep -h "facade families used" "$VP/logs/final_capture_skyscraper.log" | grep -v "^GolfArcade\|Filename" | sort -u | sed 's/^/   /'
grep -h "VenueBuild\] sky: \(cloud sea\|cumulus\)" "$VP/logs/final_capture_skyscraper.log" | sort -u | sed 's/^/   /'
} > "$OUT" 2>&1
cat "$OUT"
