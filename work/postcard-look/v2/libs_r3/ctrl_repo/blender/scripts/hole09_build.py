YD = P.YD
SKIN_DISP_M = (0.3, 2.3)       # round 3: the strata skin is displaced further out (round 2 0.3-1.7 m, round 1 0.2-1.2 m): a more jagged cliff plan (reviewer: near-straight profile, still a plank wall)
SKIN_MAX_OUT_M = 3.4          # lib default 2.6: lets the headlands of the larger displacement stand out (round 3)
SKIN_JAG_M = 3.6              # lib default 2.0 (round 2: 2.6)
SKIN_STEP_M = 2.4             # strata skin column spacing (m): 1.5 gives 79k tris, 2.0 about 60k (the triangle budget is 250k with the props)
TEE_BOX_M = (10.4, 13.2)      # design 12 x 16 yd; the largest rounded rectangle that stays inside the 9 yd fairway round end

ARGS = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []


def opt(name, default=None):
    return ARGS[ARGS.index(name) + 1] if name in ARGS and ARGS.index(name) + 1 < len(ARGS) else default


OUT = os.path.abspath(opt("--out")) if opt("--out") else None
RENDER = "--no-render" not in ARGS
QA = "--no-qa" not in ARGS
GATES = []


def gate(name, ok, detail):
    GATES.append((name, bool(ok), str(detail)))
    print(f"GATE: {name} {'PASS' if ok else 'FAIL'} - {detail}", flush=True)


# ----------------------------------------------------------------------------------------------- overview framing
def frame_overview(D, rot_deg=(50.0, 0.0, 20.0), margin=1.06, height_px=1700):
    """CAM_HOLE_OVERVIEW like the lib (orthographic, same angle as hole 7) but framed for a tall thin island: the image is
    as wide as the island's projection needs instead of the lib's square 1:1 frame. Returns the (width, height) in pixels."""
    cam = bpy.data.objects["CAM_HOLE_OVERVIEW"]
    rot = Matrix.Rotation(math.radians(rot_deg[2]), 3, 'Z') @ Matrix.Rotation(math.radians(rot_deg[0]), 3, 'X')
    right, up, view = rot @ Vector((1, 0, 0)), rot @ Vector((0, 1, 0)), rot @ Vector((0, 0, -1))
    corners = [Vector((x, y, z)) for x, y in (P.m(a, b) for a, b in D.SHORE) for z in (D.play_z + 10.0, -6.0)]
    rs = [c.dot(right) for c in corners]
    us = [c.dot(up) for c in corners]
    wr, hu = (max(rs) - min(rs)) * margin, (max(us) - min(us)) * margin
    cam.rotation_euler = rot.to_euler()
    cam.location = right * ((min(rs) + max(rs)) / 2) + up * ((min(us) + max(us)) / 2) - view * 1500.0
    res = (int(round(height_px * wr / hu / 2) * 2), height_px)
    cam.data.ortho_scale = max(wr, hu * res[0] / res[1]) if res[0] >= res[1] else hu
    return res


# ----------------------------------------------------------------------------------------------- build
t_start = time.time()
D = P.start("hole09_design", out_dir=OUT)
D.mod.SCENERY["tee_box_m"] = TEE_BOX_M                       # lib key: tee box width x depth in metres (set at runtime, not in the design file)

# 1. the scoring build (unchanged): flat top at PLAY_Z, banded cliffs, play surfaces, one ocean plane, gameplay placeholders, cameras
P.build_terrain(D)
P.build_play_surfaces(D)
P.build_water(D, shallow_material=None, foam_material=None)  # the ocean plane only: L.build_sea replaces it by the graded grid + thin shelf + sparse surf
P.build_gameplay(D)
P.build_cameras_and_light(D)

# 2. the look pass
L.look_materials(D)
snap = L.snapshot_ground(D)
L.retarget_materials(D)
# REPAIR ROUND 1 (finding 'straight seam across the tee frame'): the tee box was LK_GREEN (planar UV, no mow stripes) next to the LK_FAIRWAY ribbon (centerline UV, stripes), a ruler-straight step
# in grass tone. On LK_FAIRWAY the centerline UVs make the stripes run on under the tee ball. postcard_look_verify allows {LK_GREEN, LK_FAIRWAY} on TEE_BOX; the lie is Hole.LieAt (untouched).
tee_ob = bpy.data.objects["TEE_BOX"]
tee_ob.data.materials[0] = L.look_material("LK_FAIRWAY", D)
try:                                                          # shading only (vertices / faces untouched): the rim vertices of the 10 cm riser must not average the riser normal into the top face
    tee_ob.data.shade_smooth()
    tee_ob.data.set_sharp_from_angle(angle=math.radians(30.0))
except Exception as exc:                                      # pragma: no cover
    print("[hole09] tee box shading not changed:", exc)
tee_ob.data.update()
poly = HL.scrub_polygon_yd(D)
n_core, n_soft = HL.assign_scrub_soft(D, poly)                # the dry olive ridge: a material only (core polygon + a patchy soft zone), the lie stays Rough
n_scrub = n_core + n_soft
scn = HL.build_scenery(D)                                     # sea stacks, ruin, rocks, ridge outcrops + knolls, the shrub / rock chain over the scrub boundary, thickets, tufts
cover = scn["cover"]
n_chip, chip_verts = HL.chip_blocks(D)                        # round 2: the fallen ruin blocks / rubble get chipped meshes (>= 64 welded vertices, was 24)
sand_objs, sand_info = HL.build_sand_overlay(D)               # round 2: DRESS_SAND_nn lobes on the bunker lips (visual only)
PL.assert_no_legacy_rocks(D)                                  # raises if any icosahedron / < 60 vertex rock is left
skin = L.build_cliff_skin(D, style="strata", step_m=SKIN_STEP_M, disp_m=SKIN_DISP_M, jag_m=SKIN_JAG_M, max_out_m=SKIN_MAX_OUT_M)
bpy.context.view_layer.update()                               # LIB BUG workaround: build_sea reads matrix_world of the rocks just placed (stale = identity until the view layer updates), see LIB_BUGS.md
L.build_sea(D)                                                # AFTER the skin and the rocks (it measures both); the channel gap is an automatic shelf pocket
L.retarget_materials(D)
L.assign_uvs(D)                                               # LAST
# REPAIR ROUND 1 (finding 'island reads flat: no darker fringe / rough at the sides of the near ground'): the visible part of FAIRWAY_FIRSTCUT is the 3 yd collar of ROUGH LIE round the fairway (the fairway lie is under
# the FAIRWAY mesh, 6 cm higher), so it takes the rough material: the mown ribbon is bounded by darker rough like split.jpg. The material is swapped AFTER assign_uvs: the collar keeps its CENTERLINE UVs (smooth over the
# long n-gons of that mesh; planar+warp UVs of LK_ROUGH streak across them) at the fairway tile (10 m, 1.2 x the rough contract density: UV_DENSITY allows 1/3 .. 3 x). Vertices / faces / heights untouched.
bpy.data.objects["FAIRWAY_FIRSTCUT"].data.materials[0] = L.look_material("LK_ROUGH", D)

ok, detail = L.compare_ground(D, snap)
gate("H_PLAY_UNCHANGED_INBUILD", ok, "play surfaces vs the snapshot taken before any look code: " + detail)
if QA:
    for name, ok_, detail in L.audit_look(D) + L.v2_gates(D, pockets=L.sea_pockets(D, None)):
        gate(name, ok_, detail)
    tort = L.skin_tortuosity(D)
    gate("SKIN_JAGGED", tort is not None and tort >= 1.15, f"strata skin mid-row plan tortuosity {tort:.3f} (>= 1.15; the v1 skin measured 1.03; 1.000 = a smooth curtain)")

st = P.stats(D)
print(f"HOLE09 stats: {st['objects']} objects, {st['meshes']} meshes, {st['tris']} tris ({st['ground_tris']} ground); "
      f"scrub faces {n_scrub}; build {time.time() - t_start:.0f}s", flush=True)

if RENDER:
    P.render_overview(D, res=frame_overview(D))
blend = P.save(D)
fbx = L.export_look_fbx(D)
print(f"HOLE09 wrote {blend} and {fbx} ({os.path.getsize(fbx) / 1048576:.2f} MB)", flush=True)
fails = [n for n, ok_, _ in GATES if not ok_]
print(f"HOLE09 in-build gates: {len(GATES)} run, {len(fails)} FAIL {fails}", flush=True)
